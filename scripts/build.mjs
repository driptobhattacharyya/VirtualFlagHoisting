// Copies the MediaPipe runtime from node_modules into public/vendor/ and
// fetches the hand landmarker model, so the deployed site serves all of its
// own code. public/vendor/ is generated and not committed.
import { execFileSync } from 'node:child_process';
import { copyFile, mkdir, rename, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules', '@mediapipe', 'tasks-vision');
const vendor = join(root, 'public', 'vendor');

const MODEL_REMOTE =
  'https://storage.googleapis.com/mediapipe-models/hand_landmarker/hand_landmarker/float16/1/hand_landmarker.task';
const MODEL_LOCAL = 'models/hand_landmarker.task';

// Cloudflare Workers static assets: 25 MiB per file.
const MAX_ASSET_BYTES = 25 * 1024 * 1024;

const files = [
  ['vision_bundle.mjs', 'mediapipe/vision_bundle.mjs'],
  ['wasm/vision_wasm_internal.js', 'mediapipe/wasm/vision_wasm_internal.js'],
  ['wasm/vision_wasm_internal.wasm', 'mediapipe/wasm/vision_wasm_internal.wasm'],
  // Fallback the library picks by itself on browsers without WebAssembly SIMD.
  ['wasm/vision_wasm_nosimd_internal.js', 'mediapipe/wasm/vision_wasm_nosimd_internal.js'],
  ['wasm/vision_wasm_nosimd_internal.wasm', 'mediapipe/wasm/vision_wasm_nosimd_internal.wasm'],
];

async function size(path) {
  try {
    return (await stat(path)).size;
  } catch {
    return 0;
  }
}

async function download(url, dest) {
  const tmp = `${dest}.tmp`;
  try {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    await writeFile(tmp, Buffer.from(await response.arrayBuffer()));
  } catch (fetchError) {
    // Node's fetch ignores HTTPS_PROXY; curl honours it.
    try {
      execFileSync('curl', ['-fsSL', '--retry', '2', '-o', tmp, url], { stdio: 'ignore' });
    } catch {
      await rm(tmp, { force: true });
      throw fetchError;
    }
  }
  await rename(tmp, dest);
}

for (const [from, to] of files) {
  const dest = join(vendor, to);
  await mkdir(dirname(dest), { recursive: true });
  await copyFile(join(pkg, from), dest);
}

// The model: self-host when it can be downloaded, otherwise let the browser
// load it from Google's storage at runtime.
const modelPath = join(vendor, MODEL_LOCAL);
await mkdir(dirname(modelPath), { recursive: true });
let modelUrl = MODEL_LOCAL;
if ((await size(modelPath)) < 1024 * 1024) {
  try {
    await download(MODEL_REMOTE, modelPath);
    if ((await size(modelPath)) < 1024 * 1024) throw new Error('download is too small');
  } catch (error) {
    await rm(modelPath, { force: true });
    modelUrl = MODEL_REMOTE;
    console.warn(`! Could not download the hand model (${error.message}).`);
    console.warn('  The site will load it from storage.googleapis.com at runtime instead.');
  }
}

await writeFile(
  join(vendor, 'config.js'),
  `// Generated by scripts/build.mjs\nexport const MODEL_URL = ${JSON.stringify(modelUrl)};\n`,
);

const outputs = [...files.map(([, to]) => to), 'config.js'];
if (modelUrl === MODEL_LOCAL) outputs.push(MODEL_LOCAL);
for (const file of outputs) {
  const bytes = await size(join(vendor, file));
  if (bytes > MAX_ASSET_BYTES) {
    throw new Error(`${file} is ${bytes} bytes, over the 25 MiB Workers asset limit`);
  }
  console.log(`public/vendor/${file}  ${(bytes / 1024).toFixed(0)} KiB`);
}
