// Copies the MediaPipe runtime from node_modules into public/vendor/ and
// fetches the hand landmarker model, so the deployed site serves all of its
// own code. public/vendor/ and public/js/vendor.js are generated and not
// committed.
//
// Everything under public/vendor/ lives in a directory named after its
// version (the npm package version, or the model's hash), so those files can
// be cached for a long time and a browser can never combine a cached file
// from one MediaPipe release with a fresh one from another. The only pointer
// to them is public/js/vendor.js, which is revalidated on every load.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules', '@mediapipe', 'tasks-vision');
const vendor = join(root, 'public', 'vendor');

const MODEL_REMOTE =
  'https://storage.googleapis.com/mediapipe-models/hand_landmarker/hand_landmarker/float16/1/hand_landmarker.task';
// SHA-256 of that file. Anything else is rejected, cached copies included.
const MODEL_SHA256 = 'fbc2a30080c3c557093b5ddfc334698132eb341044ccee322ccf8bcf3607cde1';

// Cloudflare Workers static assets: 25 MiB per file.
const MAX_ASSET_BYTES = 25 * 1024 * 1024;

const { version } = JSON.parse(await readFile(join(pkg, 'package.json'), 'utf8'));
const mediapipeDir = `mediapipe-${version}`;
const modelFile = `models/${MODEL_SHA256.slice(0, 16)}/hand_landmarker.task`;

const files = [
  ['vision_bundle.mjs', 'vision_bundle.mjs'],
  ['wasm/vision_wasm_internal.js', 'wasm/vision_wasm_internal.js'],
  ['wasm/vision_wasm_internal.wasm', 'wasm/vision_wasm_internal.wasm'],
  // Fallback the library picks by itself on browsers without WebAssembly SIMD.
  ['wasm/vision_wasm_nosimd_internal.js', 'wasm/vision_wasm_nosimd_internal.js'],
  ['wasm/vision_wasm_nosimd_internal.wasm', 'wasm/vision_wasm_nosimd_internal.wasm'],
].map(([from, to]) => [from, `${mediapipeDir}/${to}`]);

async function size(path) {
  try {
    return (await stat(path)).size;
  } catch {
    return 0;
  }
}

async function sha256(path) {
  try {
    return createHash('sha256').update(await readFile(path)).digest('hex');
  } catch {
    return null;
  }
}

async function download(url, dest) {
  const tmp = `${dest}.tmp`;
  try {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    await writeFile(tmp, Buffer.from(await response.arrayBuffer()));
  } catch (fetchError) {
    // Node's fetch ignores HTTPS_PROXY; curl honours it.
    try {
      execFileSync('curl', ['-fsSL', '--retry', '2', '-o', tmp, url], { stdio: 'ignore' });
    } catch {
      await rm(tmp, { force: true });
      throw fetchError;
    }
  }
  const actual = await sha256(tmp);
  if (actual !== MODEL_SHA256) {
    await rm(tmp, { force: true });
    throw new Error(`checksum mismatch: got ${actual}`);
  }
  await rename(tmp, dest);
}

// Keep a verified model from an earlier build, drop everything else so no
// directory of an older MediaPipe version is left behind to be deployed.
const modelPath = join(vendor, modelFile);
const cachedModel = (await sha256(modelPath)) === MODEL_SHA256 ? await readFile(modelPath) : null;
await rm(vendor, { recursive: true, force: true });
await mkdir(dirname(modelPath), { recursive: true });
if (cachedModel) await writeFile(modelPath, cachedModel);

for (const [from, to] of files) {
  const dest = join(vendor, to);
  await mkdir(dirname(dest), { recursive: true });
  await copyFile(join(pkg, from), dest);
}

// The model: self-host when it can be downloaded and verified, otherwise let
// the browser load it from Google's storage at runtime.
let modelUrl = `../vendor/${modelFile}`;
if (!cachedModel) {
  try {
    await download(MODEL_REMOTE, modelPath);
  } catch (error) {
    await rm(join(vendor, 'models'), { recursive: true, force: true });
    modelUrl = MODEL_REMOTE;
    console.warn(`! Could not fetch a verified hand model (${error.message}).`);
    console.warn('  The site will load it from storage.googleapis.com at runtime instead.');
  }
}

// URLs are relative to public/js/, where tracker.js imports this module.
await writeFile(
  join(root, 'public', 'js', 'vendor.js'),
  [
    '// Generated by scripts/build.mjs. Do not edit.',
    `export const MEDIAPIPE_URL = ${JSON.stringify(`../vendor/${mediapipeDir}/`)};`,
    `export const MODEL_URL = ${JSON.stringify(modelUrl)};`,
    '',
  ].join('\n'),
);

const outputs = files.map(([, to]) => to);
if (modelUrl !== MODEL_REMOTE) outputs.push(modelFile);
for (const file of outputs) {
  const bytes = await size(join(vendor, file));
  if (bytes > MAX_ASSET_BYTES) {
    throw new Error(`${file} is ${bytes} bytes, over the 25 MiB Workers asset limit`);
  }
  console.log(`public/vendor/${file}  ${(bytes / 1024).toFixed(0)} KiB`);
}
console.log('public/js/vendor.js');
